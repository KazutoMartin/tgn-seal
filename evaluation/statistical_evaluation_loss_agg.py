import argparse
import csv
import pickle
from pathlib import Path

import numpy as np
from scipy.stats import wilcoxon

# =====================================================
# Configuration
#
# 2x2 Matrix: Loss (bce, focal) x Aggregator (last, attn)
# Fixed: target pooling, hybrid hard negative sampling, nocache, 2-hop
# =====================================================

LOSS_VARIANTS = ["bce", "focal"]
AGGREGATOR_VARIANTS = ["last", "attn"]

POOLING = "target"
SAMPLER = "hybrid"
CACHE_MODE = "nocache"
HOP_DEPTH = "2hop"

AVAILABLE_KEY = ["val_aps", "new_nodes_val_aps"]
AP_KEY = AVAILABLE_KEY[0]
MODE = "mean"
ALPHA = 0.05

EXPERIMENTS = {
    "TGN_SEAL-Dept1": dict(dataset="dept1", base_prefix="tgn-seal-dept1", n_runs=2),
    "TGN_SEAL-Dept2": dict(dataset="dept2", base_prefix="tgn-seal-dept2", n_runs=2),
    "TGN_SEAL-Dept3": dict(dataset="dept3", base_prefix="tgn-seal-dept3", n_runs=2),
    "TGN_SEAL-Dept4": dict(dataset="dept4", base_prefix="tgn-seal-dept4", n_runs=2),
}


# =====================================================
# Helper Functions
# =====================================================

def read_pickle(path):
    with open(path, "rb") as f:
        return pickle.load(f)


def extract_ap(res, key=AP_KEY, mode="best"):
    aps = np.asarray(res[key])
    if mode == "best":
        return aps.max()
    elif mode == "mean":
        return aps.mean()
    else:
        raise ValueError("mode must be 'best' or 'mean'")


def extract_training_stats(res):
    epoch_times = np.asarray(res["epoch_times"], dtype=float)
    return epoch_times.mean(), epoch_times.sum(), len(epoch_times)


def paths_for(exp, loss_variant, agg_variant):
    """Reproduces the exact results path format generated by train_self_supervised.py."""
    # Prefix format: {base_prefix}-{loss}-{agg}-target-hybrid-nocache-2hop
    prefix = f"{exp['base_prefix']}-{loss_variant}-{agg_variant}-{POOLING}-{SAMPLER}-{CACHE_MODE}-{HOP_DEPTH}"
    paths = []
    for run_idx in range(exp["n_runs"]):
        filename = f"{prefix}_{run_idx}.pkl" if run_idx > 0 else f"{prefix}.pkl"
        paths.append(f"results/{filename}")
    return paths


def existing_paths(paths):
    missing = [p for p in paths if not Path(p).exists()]
    return [p for p in paths if Path(p).exists()], missing


# =====================================================
# Main Evaluation
# =====================================================

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--csv", 
        type=str, 
        default="loss_aggregator_ablation_summary.csv", 
        help="Path to write output summary table."
    )
    args = parser.parse_args()

    print("=" * 75)
    print(f"AP evaluation mode: {MODE.upper()}  |  AP source key: {AP_KEY}")
    print("Benchmarking Loss (BCE vs Focal) x Aggregator (Last vs Attention)")
    print(f"Fixed Context: {POOLING} pooling, {SAMPLER} sampler, {CACHE_MODE}, {HOP_DEPTH}")
    print("=" * 75)

    csv_rows = []

    for exp_name, exp in EXPERIMENTS.items():
        print(f"\n{'-' * 75}\n{exp_name} (dataset={exp['dataset']})\n{'-' * 75}")

        variant_aps = {}
        variant_times = {}

        for loss in LOSS_VARIANTS:
            for agg in AGGREGATOR_VARIANTS:
                combo_key = f"{loss}-{agg}"
                paths = paths_for(exp, loss, agg)
                found, missing = existing_paths(paths)

                if not found:
                    print(f"  [{combo_key:12s}] SKIPPED -- no result files found, e.g. {paths[0]}")
                    continue
                if missing:
                    print(f"  [{combo_key:12s}] partial: {len(found)}/{len(paths)} run(s) found -- using available runs")

                results = [read_pickle(p) for p in found]
                aps = np.array([extract_ap(r, mode=MODE) for r in results])
                times = np.array([extract_training_stats(r) for r in results])

                variant_aps[combo_key] = aps
                variant_times[combo_key] = times

                print(
                    f"  [{combo_key:12s}] AP: {aps.mean():.4f} ± {aps.std():.4f}"
                    f"   |  mean epoch time: {times[:, 0].mean():.2f}s"
                    f"   |  mean epochs to converge: {times[:, 2].mean():.1f}"
                )

                csv_rows.append({
                    "experiment": exp_name,
                    "dataset": exp["dataset"],
                    "loss": loss,
                    "aggregator": agg,
                    "pooling": POOLING,
                    "sampler": SAMPLER,
                    "cache_mode": CACHE_MODE,
                    "hop": HOP_DEPTH,
                    "n_runs_found": len(found),
                    "ap_mean": aps.mean(),
                    "ap_std": aps.std(),
                    "mean_epoch_time_s": times[:, 0].mean(),
                    "mean_total_time_s": times[:, 1].mean(),
                    "mean_epochs_to_converge": times[:, 2].mean(),
                })

        # Paired comparison against the default baseline configuration (BCE loss + Last message aggregator)
        baseline_key = "bce-last"
        if baseline_key in variant_aps:
            baseline_aps = variant_aps[baseline_key]
            for combo_key, eval_aps in variant_aps.items():
                if combo_key == baseline_key:
                    continue
                if len(baseline_aps) < 2 or len(eval_aps) < 2:
                    print(f"  [baseline vs {combo_key:12s}] fewer than 2 paired samples found -- skipping Wilcoxon test")
                    continue
                if len(baseline_aps) != len(eval_aps):
                    print(f"  [baseline vs {combo_key:12s}] unequal sample counts ({len(baseline_aps)} vs {len(eval_aps)}) -- skipping Wilcoxon test")
                    continue
                try:
                    stat, p_value = wilcoxon(eval_aps, baseline_aps)
                    direction = "no significant AP difference"
                    if p_value < ALPHA:
                        direction = "AP significantly DIFFERENT from baseline" if eval_aps.mean() != baseline_aps.mean() else "AP tied"

                    print(f"  [baseline vs {combo_key:12s}] p={p_value:.4e} ({direction})")
                except ValueError as e:
                    print(f"  [baseline vs {combo_key:12s}] Wilcoxon test not applicable ({e})")

    if args.csv and csv_rows:
        with open(args.csv, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(csv_rows[0].keys()))
            writer.writeheader()
            writer.writerows(csv_rows)
        print(f"\nWrote {len(csv_rows)} rows to {args.csv}")
    elif args.csv:
        print(f"\nNo result files found yet -- {args.csv} not written.")


if __name__ == "__main__":
    main()